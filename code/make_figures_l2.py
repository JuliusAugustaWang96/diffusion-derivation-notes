    post_m, post_v = 1.2, 0.2

    def kl(m1, v1, m2, v2):
        return 0.5 * (v1 / v2 + (m1 - m2) ** 2 / v2 - 1 + math.log(v2 / v1))

    rows = []
    for name, mq, vq in (("$q=\\mathcal{N}(0,1)$\n（等于先验）", 0.0, 1.0), ("$q=\\mathcal{N}(1,0.5)$", 1.0, 0.5),
                         ("$q=\\mathcal{N}(1.2,0.2)$\n（等于后验）", 1.2, 0.2)):
        rec = -0.5 * math.log(2 * math.pi) - 0.5 * ((x - a * mq) ** 2 + a * a * vq)
        lb = rec - kl(mq, vq, 0, 1)
        rows.append((name, lb, kl(mq, vq, post_m, post_v)))
        print(f"  l2_fig6: {name.splitlines()[0]}: Lb = {lb:.4f}, KL = {rows[-1][2]:.4f}, sum = {lb + rows[-1][2]:.4f}")
    fig, ax = plt.subplots(figsize=(16 * CM, 6.8 * CM))
    xs = np.arange(3)
    lbs = np.array([r[1] for r in rows])
    gaps = np.array([r[2] for r in rows])
    floor = -9.0                                     # common baseline, as in the slide's diagram: bars start here
    ax.bar(xs, lbs - floor, width=0.42, bottom=floor, color=CORAL, alpha=0.85, label="下界 $L_b$（柱顶的位置）")
    ax.bar(xs, gaps, width=0.42, bottom=lbs, color=TEAL, alpha=0.85,
           label="$\\mathrm{KL}(q(z\\mid x)\\Vert P(z\\mid x))$")
    ax.axhline(log_px, color=BLUE, lw=1.2, ls="--")
    ax.text(-0.58, log_px + 0.15, f"$\\log P(x)={log_px:.4f}$，与 $q$ 无关", color=BLUE, fontsize=7.5, va="bottom")
    for k, (name, lb, gap) in enumerate(rows):
        if gap > 1:                                  # room for both labels beside the bar
            ax.text(k + 0.24, lb, f"$L_b={lb:.4f}$", ha="left", va="center", fontsize=7.5, color=CORAL)
            ax.text(k + 0.24, lb + gap / 2, f"KL = {gap:.4f}", ha="left", va="center", fontsize=7.5, color=TEAL)
        else:                                        # thin or empty KL segment: KL above the line, Lb below it
            ax.text(k + 0.24, lb - 0.5, f"$L_b={lb:.4f}$", ha="left", va="center", fontsize=7.5, color=CORAL)
            ax.text(k + 0.24, log_px + 0.4, f"KL = {gap:.4f}" if gap > 0.05 else "KL = 0", ha="left", va="center",
                    fontsize=7.5, color=TEAL)
    ax.set_xticks(xs, [r[0] for r in rows], fontsize=7.5)
    ax.set_ylim(floor, 0)
    ax.set_xlim(-0.6, 3.5)
    ax.tick_params(labelsize=7.5)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=7.5, frameon=False, loc="lower right")
    ax.set_title("同一个观测 $x=3$：换不同的 $q$，$\\log P(x)$ 不变，只是 $L_b$ 与 KL 的分配不同", fontsize=8.5,
                 loc="left")
    fig.tight_layout()
    save(fig, "l2_fig6_elbo_gap.png")


