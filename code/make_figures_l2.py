def box(ax, x, y, w, h, text, kind="learn", size=8.5, bold=False):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.12",
                                fc=FILL[kind], ec=EDGE[kind], lw=1.0))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=size,
            fontweight="bold" if bold else "normal", color="#2C2C2A")


def arrow(ax, x1, y1, x2, y2, text=None, color="#444441", dy=0.18, size=7.5, style="-|>", ls="-"):
    ax.annotate("", xy=(x2, y2), xytext=(x1, y1),
                arrowprops=dict(arrowstyle=style, color=color, lw=1.0, shrinkA=0, shrinkB=0, linestyle=ls))
    if text:
        ax.text((x1 + x2) / 2, (y1 + y2) / 2 + dy, text, ha="center", va="bottom", fontsize=size, color=color)


def thumb(ax, img, x, y, s, cmap="gray_r", vmax=1.0):
    ax.imshow(img, extent=(x, x + s, y, y + s), interpolation="nearest", zorder=2, cmap=cmap, vmin=0, vmax=vmax)
    ax.add_patch(plt.Rectangle((x, y), s, s, fill=False, ec=GRAY, lw=0.6, zorder=3))


def save(fig, name):
    fig.savefig(OUT / name, dpi=200)
    plt.close(fig)
    print("  saved", OUT / name)


def moon(kind, n=48):
    """Synthetic moon on a black sky: 'full' = whole disc lit, 'half' = right half lit (a first-quarter moon),
    'gibbous' = a real phase between the two (the terminator is a half-ellipse). Values in [0, 1]."""
    yy, xx = (np.mgrid[0:n, 0:n] + 0.5) / n * 2 - 1
    disc = xx ** 2 + yy ** 2 < 0.8 ** 2
    if kind == "full":
        lit = disc
    elif kind == "half":
        lit = disc & (xx > 0)
    else:
        half_width = 0.8 * np.sqrt(np.clip(1 - (yy / 0.8) ** 2, 0, 1))
        lit = disc & (xx > -0.55 * half_width)
    img = np.where(lit, 0.92, 0.0)
    return img


