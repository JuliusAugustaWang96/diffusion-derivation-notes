def fig_variance():
    s = np.linspace(-3, 2.2, 600)
    fig, axes = plt.subplots(1, 2, figsize=(16 * CM, 6.6 * CM))
    ax = axes[0]
    ax.plot(s, np.exp(s), color=BLUE, lw=1.2, label="$\\exp(\\sigma)$")
    ax.plot(s, 1 + s, color=CORAL, lw=1.2, label="$1+\\sigma$")
    ax.plot(s, np.exp(s) - (1 + s), color=TEAL, lw=1.8, label="$\\exp(\\sigma)-(1+\\sigma)$")
    ax.axhline(0, color=GRAY, lw=0.6)
    ax.axvline(0, color=GRAY, lw=0.6)
    ax.plot(0, 0, "o", color=TEAL, ms=4)
    ax.set_ylim(-3, 6)
    ax.set_xlabel("$\\sigma$")
    ax.set_title("(a) 讲义中的方差项：只在 $\\sigma=0$ 处取最小值 0", fontsize=8.5, loc="left")
    ax.legend(fontsize=7, frameon=False, loc="lower right", handlelength=1.6, labelspacing=0.3)
    ax.annotate("$\\sigma\\to-\\infty$：几乎不加噪声，\n这一项越来越大", xy=(-2.6, math.exp(-2.6) + 1.6), xytext=(-2.9, 4.4),
                fontsize=7, color="#444441", arrowprops=dict(arrowstyle="-|>", color="#444441", lw=0.7))
    ax = axes[1]
    kl_var = 0.5 * (np.exp(s) - (1 + s))                      # sigma = log variance
    kl_std = 0.5 * (np.exp(2 * s) - (1 + 2 * s))              # sigma = log standard deviation
    ax.plot(s, 2 * kl_var, color=TEAL, lw=1.8, label="讲义的式子")
    ax.plot(s, kl_var, color=BLUE, lw=1.2, ls="--", label="KL，若 $\\sigma$ 是对数方差")
    ax.plot(s, kl_std, color=PURPLE, lw=1.2, label="KL，若 $\\sigma$ 是对数标准差")
    ax.axhline(0, color=GRAY, lw=0.6)
    ax.axvline(0, color=GRAY, lw=0.6)
    ax.set_ylim(-0.2, 3.2)
    ax.set_xlabel("$\\sigma$（$m=0$）")
    ax.set_title("(b) 与一维 KL 散度对照", fontsize=8.5, loc="left")
    ax.legend(fontsize=7.5, frameon=False, loc="upper center")
    for a in axes:
        a.tick_params(labelsize=7.5)
        a.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(w_pad=1.5)
    print(f"  l2_fig4: at sigma = 1 the slide term is {math.e - 2:.4f}, KL(log variance) {0.5 * (math.e - 2):.4f}, "
          f"KL(log std) {0.5 * (math.e ** 2 - 3):.4f}")
    save(fig, "l2_fig4_variance_term.png")


