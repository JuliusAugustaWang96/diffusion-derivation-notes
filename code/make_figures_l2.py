def seven(shift=0, n=28):
    """Same digit as l2_check.py (i): a top bar and a diagonal stroke, values 0 (white) or 1 (black)."""
    img = np.zeros((n, n))
    rr, cc = np.mgrid[0:n, 0:n]
    pts = [(6, 7), (6, 20), (22, 11)]
    for (r0, c0), (r1, c1) in zip(pts, pts[1:]):
        for t in np.linspace(0, 1, 200):
            r, cl = r0 + (r1 - r0) * t, c0 + (c1 - c0) * t + shift
            img = np.maximum(img, (((rr - r) ** 2 + (cc - cl) ** 2) <= 1.3 ** 2).astype(float))
    return img


def fig_pixels():
    target = seven()
    ink = np.argwhere(target > 0)
    end = ink[ink[:, 0].argmax()]
    realistic = target.copy()
    realistic[end[0] + 1, end[1]] = 1
    fake = target.copy()
    fake[12, 24] = 1
    shifted, blurred = seven(1), (seven(-1) + target + seven(1)) / 3
    se = lambda a: float(((a - target) ** 2).sum())
    panels = [(target, "目标", None), (realistic, "延长笔画\n（像真的）", se(realistic)),
              (fake, "孤立像素\n（一眼假）", se(fake)), (shifted, "右移 1 像素的\n清晰的 7", se(shifted)),
              (blurred, "三个位置的平均\n（模糊的 7）", se(blurred))]
    fig = plt.figure(figsize=(16 * CM, 5.6 * CM))
    for k, (img, title, err) in enumerate(panels):
        a = fig.add_axes([0.02 + 0.196 * k, 0.2, 0.16, 0.5])
        a.imshow(img, cmap="gray_r", vmin=0, vmax=1, interpolation="nearest")
        a.set_xticks([]), a.set_yticks([])
        a.set_title(title, fontsize=7.5)
        if err is not None:
            a.text(14, 30.5, f"平方误差 {err:.2f}" if err % 1 else f"平方误差 {err:.0f}", ha="center", va="top",
                   fontsize=7.5)
        if k in (1, 2):
            r, c = (end[0] + 1, end[1]) if k == 1 else (12, 24)
            a.add_patch(plt.Circle((c, r), 2.2, fill=False, ec=CORAL, lw=1.0))
    fig.text(0.02, 0.9, "(a) 差一个像素：两张图的误差都是 1，但一张像真的，一张一眼假", fontsize=8.5)
    fig.text(0.41, 0.9, "", fontsize=8.5)
    fig.text(0.61, 0.9, "(b) 逐像素比较时，模糊的 7 反而误差更小", fontsize=8.5)
    print(f"  l2_fig7: squared errors {[round(p[2], 2) for p in panels[1:]]}")
    save(fig, "l2_fig7_one_pixel.png")


