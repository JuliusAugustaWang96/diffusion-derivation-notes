    sd = np.array([0.45, 0.30, 0.50, 0.70, 0.25])
    xs = np.linspace(-5, 5.5, 1200)
    comp = pm[:, None] * np.exp(-(xs[None] - mu[:, None]) ** 2 / (2 * sd[:, None] ** 2)) / np.sqrt(2 * np.pi * sd[:, None] ** 2)
    fig = plt.figure(figsize=(16 * CM, 8.2 * CM))
    ax = fig.add_axes([0.07, 0.47, 0.40, 0.44])
    for k in range(5):
        ax.plot(xs, comp[k], color=TEAL, lw=0.9)
    ax.plot(xs, comp.sum(0), color="#2C2C2A", lw=1.6)
    ax.set_title("(a) 高斯混合：5 个分量（细线）相加得到 $P(x)$（粗线）", fontsize=8, loc="left")
    ax.set_xticks([]), ax.set_yticks([])
    ax.set_ylabel("$P(x)$", fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    bx = fig.add_axes([0.07, 0.16, 0.40, 0.2])
    bx.bar(np.arange(1, 6), pm, color=BLUE, width=0.5)
    bx.set_xticks(range(1, 6))
    bx.set_yticks([])
    bx.set_ylabel("$P(m)$", fontsize=8)
    bx.set_xlabel("类别 $m$（整数）", fontsize=8)
    bx.spines[["top", "right"]].set_visible(False)
    bx.tick_params(labelsize=7.5)

    def mu_net(z):
        return z + 1.8 * np.sin(2.8 * z + 1.0)                    # same function as l2_check.py (e)
    sig = 0.2
    zs = np.linspace(-6, 6, 6001)
    pz = np.exp(-zs ** 2 / 2) / math.sqrt(2 * math.pi)
    xg = np.linspace(-5, 5.5, 1200)
    lik = np.exp(-(xg[:, None] - mu_net(zs)[None]) ** 2 / (2 * sig ** 2)) / math.sqrt(2 * math.pi * sig ** 2)
    px = trap(lik * pz[None], zs, axis=1)
    ax = fig.add_axes([0.57, 0.47, 0.40, 0.44])
    for z0 in (-1.6, -1.0, -0.5, 0.0, 0.4, 0.8, 1.3):
        w0 = math.exp(-z0 ** 2 / 2) / math.sqrt(2 * math.pi) * 0.22
        ax.plot(xg, w0 * np.exp(-(xg - mu_net(z0)) ** 2 / (2 * sig ** 2)) / math.sqrt(2 * math.pi * sig ** 2),
                color=TEAL, lw=0.8)
    ax.plot(xg, px, color="#2C2C2A", lw=1.6)
    ax.set_title("(b) VAE：每个 $z$ 对应一个高斯，积分得 $P(x)$", fontsize=8, loc="left")
    ax.set_xticks([]), ax.set_yticks([])
    ax.set_ylabel("$P(x)$", fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    cx = fig.add_axes([0.57, 0.16, 0.40, 0.2])
    zz = np.linspace(-2.6, 2.6, 400)
    cx.plot(zz, mu_net(zz), color=BLUE, lw=1.3)
    cx.set_xlabel("$z\\sim\\mathcal{N}(0,1)$；曲线是代替网络的函数 $\\mu(z)$", fontsize=7.5)
    cx.set_ylabel("$\\mu(z)$", fontsize=8)
    cx.tick_params(labelsize=7.5)
    cx.spines[["top", "right"]].set_visible(False)
    peaks = [i for i in np.where((px[1:-1] > px[:-2]) & (px[1:-1] > px[2:]))[0] + 1 if px[i] > 0.05 * px.max()]
    print("  l2_fig5: peaks of the infinite mixture at x =", [round(float(xg[i]), 2) for i in peaks])
    save(fig, "l2_fig5_mixtures.png")


