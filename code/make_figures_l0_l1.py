EDGE = {"learn": BLUE, "fixed": CORAL, "latent": TEAL, "data": GRAY}

T = 1000
BETA = np.linspace(1e-4, 0.02, T)
ALPHA = 1.0 - BETA
ABAR = np.cumprod(ALPHA)


def abar(t):
    return 1.0 if t == 0 else float(ABAR[t - 1])


def scene(size=64):
    """Synthetic scene used in fig 2 and fig 3: sky, sun, two hills; pixel values in [-1, 1] (same as the check)."""
    yy, xx = np.mgrid[0:size, 0:size] / (size - 1)
    img = np.empty((size, size, 3))
    img[..., 0], img[..., 1], img[..., 2] = 0.55 + 0.35 * yy, 0.75 + 0.2 * yy, 0.98 - 0.05 * yy
    sun = (xx - 0.72) ** 2 + (yy - 0.28) ** 2 < 0.13 ** 2
    img[sun] = (1.0, 0.82, 0.25)
    far = yy > 0.62 + 0.07 * np.sin(2 * np.pi * (xx * 1.3 + 0.1))
    img[far] = (0.45, 0.68, 0.40)
    near = yy > 0.78 + 0.05 * np.sin(2 * np.pi * (xx * 0.9 + 0.55))
    img[near] = (0.25, 0.52, 0.28)
    return img * 2 - 1


def show(x):
    return np.clip((x + 1) / 2, 0, 1)


def canvas(height_cm):
    fig = plt.figure(figsize=(16 * CM, height_cm * CM))
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 16)
    ax.set_ylim(0, height_cm)
    ax.axis("off")
    return fig, ax


def box(ax, x, y, w, h, text, kind="learn", size=8.5, bold=False):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.12",
                                fc=FILL[kind], ec=EDGE[kind], lw=1.0))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=size,
            fontweight="bold" if bold else "normal", color="#2C2C2A")


def arrow(ax, x1, y1, x2, y2, text=None, color="#444441", dy=0.18, size=7.5, style="-|>"):
    ax.annotate("", xy=(x2, y2), xytext=(x1, y1),
                arrowprops=dict(arrowstyle=style, color=color, lw=1.0, shrinkA=0, shrinkB=0))
    if text:
        ax.text((x1 + x2) / 2, (y1 + y2) / 2 + dy, text, ha="center", va="bottom", fontsize=size, color=color)


def thumb(ax, img, x, y, s):
    ax.imshow(img, extent=(x, x + s, y, y + s), interpolation="nearest", zorder=2)
    ax.add_patch(plt.Rectangle((x, y), s, s, fill=False, ec=GRAY, lw=0.6, zorder=3))


def save(fig, name):
    fig.savefig(OUT / name, dpi=200)
    plt.close(fig)
    print("  saved", OUT / name)


