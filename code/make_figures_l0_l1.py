def fig_reverse():
    x0 = scene()
    r = np.random.default_rng(3)
    x = r.standard_normal(x0.shape)
    keep = {1000: None, 600: None, 300: None, 150: None, 50: None}
    for t in range(T, 0, -1):
        if t in keep:
            keep[t] = x.copy()                          # x_t, the input of step t
        eps_hat = (x - math.sqrt(abar(t)) * x0) / math.sqrt(1 - abar(t))   # optimal prediction for a one-image set
        x = (x - BETA[t - 1] / math.sqrt(1 - abar(t)) * eps_hat) / math.sqrt(ALPHA[t - 1])
        if t > 1:
            x = x + math.sqrt(BETA[t - 1]) * r.standard_normal(x.shape)
    print("  l0_fig2: max |x_0 - training image| after 1000 steps =", float(np.abs(x - x0).max()))
    fig, ax = canvas(9.4)
    ax.text(0.2, 9.05, "(a) 采样算法真实运行一次（假设训练集只有这一张图，此时最优噪声预测器有闭式解）", fontsize=8.5)
    s, y = 1.75, 6.55
    frames = [(1000, keep[1000]), (600, keep[600]), (300, keep[300]), (150, keep[150]), (50, keep[50]), (0, x)]
    xs = [0.45 + 2.6 * k for k in range(6)]
    for (t, img), xx in zip(frames, xs):
        thumb(ax, show(img), xx, y, s)
        ax.text(xx + s / 2, y - 0.3, f"$x_{{{t}}}$" if t else "$x_0$", ha="center", fontsize=8.5)
    for k in range(5):
        arrow(ax, xs[k] + s + 0.1, y + s / 2, xs[k + 1] - 0.1, y + s / 2, "去噪", dy=0.08)
    ax.text(0.2, 5.25, "(b) 一步去噪的内部（算法 2 第 4 行）", fontsize=8.5)
    box(ax, 0.6, 3.25, 1.5, 0.75, "$x_t$", "data", size=9)
    box(ax, 0.6, 1.55, 1.5, 0.75, "步数 $t$", "data", size=8.5)
    box(ax, 3.2, 2.2, 2.6, 1.15, "噪声预测器\n$\\epsilon_\\theta(x_t, t)$", "learn", size=8.5)
    arrow(ax, 2.1, 3.62, 3.2, 3.0)
    arrow(ax, 2.1, 1.92, 3.2, 2.55)
    box(ax, 6.7, 2.4, 1.3, 0.75, "$\\hat{\\epsilon}$", "learn", size=9)
    arrow(ax, 5.8, 2.77, 6.7, 2.77)
    box(ax, 8.9, 2.05, 5.0, 1.45,
        "$x_{t-1}=\\frac{1}{\\sqrt{\\alpha_t}}\\left(x_t-\\frac{\\beta_t}{\\sqrt{1-\\bar{\\alpha}_t}}\\,\\hat{\\epsilon}\\right)+\\sigma_t z$",
        "fixed", size=9.5)
    arrow(ax, 8.0, 2.77, 8.9, 2.77)
    ax.annotate("", xy=(10.2, 3.5), xytext=(2.1, 3.85),
                arrowprops=dict(arrowstyle="-|>", color="#444441", lw=1.0, connectionstyle="arc3,rad=-0.12"))
    box(ax, 14.3, 2.4, 1.4, 0.75, "$x_{t-1}$", "data", size=9)
