ANG = np.deg2rad([90, 210, 330])
CEN = np.stack([np.cos(ANG), np.sin(ANG)], 1)
S = 0.1


def eps_opt(x, t):
    ab = abar(t)
    v = ab * S ** 2 + 1 - ab
    d2 = ((x[:, None, :] - math.sqrt(ab) * CEN[None]) ** 2).sum(-1)
    lw = -d2 / (2 * v)
    w = np.exp(lw - lw.max(1, keepdims=True))
    w /= w.sum(1, keepdims=True)
    return math.sqrt(1 - ab) * (x - math.sqrt(ab) * (w @ CEN)) / v


def sample(kind, n=3000):
    x = np.random.default_rng(10).standard_normal((n, 2))
    rz = np.random.default_rng(11)
    for t in range(T, 0, -1):
        e = eps_opt(x, t)
        if kind == "ddim":
            x0_hat = (x - math.sqrt(1 - abar(t)) * e) / math.sqrt(abar(t))
            x = math.sqrt(abar(t - 1)) * x0_hat + math.sqrt(1 - abar(t - 1)) * e
        else:
            x = (x - BETA[t - 1] / math.sqrt(1 - abar(t)) * e) / math.sqrt(ALPHA[t - 1])
            if kind == "ddpm" and t > 1:
                x = x + math.sqrt(BETA[t - 1]) * rz.standard_normal(x.shape)
    return x


def spread(x):
    k = ((x[:, None, :] - CEN[None]) ** 2).sum(-1).argmin(1)
    rad, spr = [], []
    for j in range(3):
        xs = x[k == j]
        m = xs.mean(0)
        rad.append(np.linalg.norm(m))
        spr.append(np.sqrt(((xs - m) ** 2).sum(1).mean() / 2))
    return float(np.mean(rad)), float(np.mean(spr))


def fig_samplers():
    r = np.random.default_rng(12)
    data = CEN[r.integers(0, 3, 3000)] + S * r.standard_normal((3000, 2))
    panels = [("训练数据", data, GRAY), ("DDPM（$\\sigma_t^2=\\beta_t$）", sample("ddpm"), BLUE),
              ("去掉 $\\sigma_t z$", sample("mean"), CORAL), ("DDIM（η = 0）", sample("ddim"), TEAL)]
    fig, axes = plt.subplots(1, 4, figsize=(16 * CM, 5.2 * CM))
    for ax, (title, x, color) in zip(axes, panels):
        rad, spr = spread(x)
        print(f"  l1_fig3: {title}: cluster radius {rad:.3f}, within-cluster std {spr:.4f}")
        ax.scatter(x[:, 0], x[:, 1], s=0.6, color=color, alpha=0.5)
        ax.add_patch(Circle((0, 0), 1.0, fill=False, ec=GRAY, lw=0.5, ls=":"))
        ax.set_title(title, fontsize=8.5)
        ax.text(0, -1.55, f"团内标准差 {spr:.3f}\n团中心半径 {rad:.2f}", ha="center", fontsize=7, color="#444441")
        ax.set_xlim(-1.45, 1.45)
